"""Smoke tests for the Compare HTML report builder.

The report assembly is a pure function (descriptor + jobs + diff keys
→ self-contained HTML bytes), so it's straightforward to stand up
without a NiceGUI app context. We pin down:

- The document is well-formed and contains the expected sections.
- Differing keys carry the ``diff`` CSS class so they render bold + red.
- The auto-print flavour ships the ``window.print()`` script; the
  default flavour does not.
- The two palettes (light / dark) produce different background colours.
"""

from __future__ import annotations

from plotly.offline import get_plotlyjs

from matofx.ui.pages.compare.field_overlay import JobFieldOutput
from matofx.ui.pages.compare.overlay import JobCsvOutput, JobHtmlOutput
from matofx.ui.pages.compare.report import (
    ReportGroup,
    ReportImage,
    ReportJobEntry,
    ReportVideo,
    _format_material_html,
    build_compare_report,
    build_multi_compare_report,
)

_MATERIAL = {
    "material_id": 3,
    "name": "Copper",
    "class": "Metals",
    "version_ordinal": 1,
    "properties": {
        "heat_capacity": {"prop_name": "Heat capacity", "value": 377.0, "unit": "J/(kg·K)"},
        "thermal_conductivity": {
            "prop_name": "Thermal conductivity",
            "value": 406.0,
            "unit": "W/(m·K)",
        },
    },
}


def test_format_material_html_pretty_prints_block() -> None:
    out = _format_material_html(_MATERIAL)
    # Summary header with name, version and class.
    assert "Copper v1" in out
    assert "class: Metals" in out
    # Properties as 'name: value unit', not the raw dict.
    assert "Heat capacity: 377.0 J/(kg·K)" in out
    assert "Thermal conductivity: 406.0 W/(m·K)" in out
    # None of the raw dict syntax leaks through.
    assert "material_id" not in out
    assert "{" not in out


def test_format_material_html_handles_formulation_list() -> None:
    out = _format_material_html([_MATERIAL, {"name": "Aluminium", "version_ordinal": 1}])
    assert "Copper v1" in out
    assert "Aluminium v1" in out


def test_format_material_html_empty_is_dash() -> None:
    assert _format_material_html([]) == "—"
    assert _format_material_html(None) == "—"


def test_format_material_html_escapes_names() -> None:
    out = _format_material_html({"name": "<b>x</b>", "properties": {}})
    assert "&lt;b&gt;" in out
    assert "<b>x</b>" not in out


def _descriptor() -> dict:
    return {
        "alias": "demo_tool",
        "name": "Demo tool",
        "input_groups": [{"name": "ambient", "label": "Ambient"}],
        "inputs": [
            {"name": "temperature", "label": "Temperature", "type": "number", "group": "ambient"},
            {"name": "pressure", "label": "Pressure", "type": "number", "group": "ambient"},
        ],
        "output_groups": [{"name": "results", "label": "Results"}],
        "outputs": [
            {"name": "yield", "label": "Yield", "type": "number", "group": "results"},
        ],
    }


def _two_jobs() -> list[ReportJobEntry]:
    return [
        ReportJobEntry(
            job_id=1001,
            job_label="Job 0001001 · run a",
            state="complete",
            inputs={"temperature": 100, "pressure": 1.0},
            output_values={"yield": 0.85},
        ),
        ReportJobEntry(
            job_id=1002,
            job_label="Job 0001002 · run b",
            state="complete",
            inputs={"temperature": 150, "pressure": 1.0},
            output_values={"yield": 0.91},
        ),
    ]


def test_report_renders_basic_shell() -> None:
    """The document carries title, job columns, and the trailing footer."""
    bytes_out = build_compare_report(
        descriptor=_descriptor(),
        jobs=_two_jobs(),
        differing_keys=set(),
        csv_outputs=[],
        theme="dark",
    )
    text = bytes_out.decode("utf-8")
    assert text.startswith("<!DOCTYPE html>")
    assert "Compare report" in text
    assert "Demo tool" in text
    assert "Job 0001001 · run a" in text
    assert "Job 0001002 · run b" in text
    assert "Generated by MATOFX" in text


def test_report_inlines_plotly_rather_than_linking_a_cdn() -> None:
    """The downloaded report plots with no network access (P-03).

    A compare report is a file that travels — attached to email, opened
    on a laptop, read on an air-gapped site. Linking plotly.js from a
    CDN gave a document whose text rendered fine and whose charts were
    blank rectangles, which is the worst failure shape available.

    The second assertion is the subtler half: the bundle must come from
    the installed ``plotly`` package, so the JavaScript always matches
    the figure JSON the Python side serialised. The old pinned CDN URL
    named plotly.js 2.35.2 while plotly 6.x emits 3.x figure schema, and
    nothing would ever have flagged the drift.
    """
    text = build_compare_report(
        descriptor=_descriptor(),
        jobs=_two_jobs(),
        differing_keys=set(),
        csv_outputs=[],
        theme="dark",
    ).decode("utf-8")

    assert '<script src="https://' not in text
    assert "cdn.plot.ly/plotly-" not in text
    # A distinctive slice of the bundle actually shipped with this install.
    assert get_plotlyjs()[:2000] in text


def test_differing_keys_get_diff_class() -> None:
    """Rows for differing fields render with the ``diff`` CSS class."""
    bytes_out = build_compare_report(
        descriptor=_descriptor(),
        jobs=_two_jobs(),
        differing_keys={"temperature", "yield"},
        csv_outputs=[],
        theme="light",
    )
    text = bytes_out.decode("utf-8")
    # Each differing key shows up at least N times where N is the number
    # of jobs (one row per job per key).
    assert text.count('class="row diff"') >= 4  # 2 keys x 2 jobs
    # Non-differing key keeps the plain "row" class.
    assert 'class="row"' in text


def test_auto_print_script_is_only_in_pdf_flavour() -> None:
    """Default HTML download has no auto-print; PDF flavour has it."""
    plain = build_compare_report(
        descriptor=_descriptor(),
        jobs=_two_jobs(),
        differing_keys=set(),
        csv_outputs=[],
        theme="dark",
        auto_print=False,
    ).decode("utf-8")
    pdf = build_compare_report(
        descriptor=_descriptor(),
        jobs=_two_jobs(),
        differing_keys=set(),
        csv_outputs=[],
        theme="dark",
        auto_print=True,
    ).decode("utf-8")
    assert "window.print" not in plain
    assert "window.print" in pdf


def test_palette_differences_show_in_css() -> None:
    """Light vs dark theme produces different page-bg colour in the CSS."""
    light_bytes = build_compare_report(
        descriptor=_descriptor(),
        jobs=_two_jobs()[:1] + _two_jobs()[1:],
        differing_keys=set(),
        csv_outputs=[],
        theme="light",
    )
    dark_bytes = build_compare_report(
        descriptor=_descriptor(),
        jobs=_two_jobs()[:1] + _two_jobs()[1:],
        differing_keys=set(),
        csv_outputs=[],
        theme="dark",
    )
    light_text = light_bytes.decode("utf-8")
    dark_text = dark_bytes.decode("utf-8")
    # Light palette page bg ≠ dark palette page bg, so the CSS strings differ.
    assert light_text != dark_text


def test_csv_outputs_render_individual_columns() -> None:
    """When csv_outputs are supplied, the individual-charts section appears."""
    csv_bytes = b"x,y\n0,1\n1,2\n2,3\n"
    csvs = [
        JobCsvOutput(
            job_id=1001,
            job_label="Job 0001001 · run a",
            csv_name="series",
            csv_filename="series.csv",
            content=csv_bytes,
        ),
        JobCsvOutput(
            job_id=1002,
            job_label="Job 0001002 · run b",
            csv_name="series",
            csv_filename="series.csv",
            content=csv_bytes,
        ),
    ]
    text = build_compare_report(
        descriptor=_descriptor(),
        jobs=_two_jobs(),
        differing_keys=set(),
        csv_outputs=csvs,
        theme="dark",
    ).decode("utf-8")
    # Merged + individual sections both appear when ≥2 jobs share a CSV.
    assert "Merged charts" in text
    assert "Individual charts" in text


def test_report_with_no_csv_outputs_skips_chart_sections() -> None:
    """Without CSV outputs the chart sections drop out cleanly."""
    text = build_compare_report(
        descriptor=_descriptor(),
        jobs=_two_jobs(),
        differing_keys=set(),
        csv_outputs=[],
        theme="dark",
    ).decode("utf-8")
    assert "Merged charts" not in text
    assert "Individual charts" not in text


