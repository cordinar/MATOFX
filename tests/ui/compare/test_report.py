def test_missing_participant_renders_aligned_placeholder() -> None:
    """A ``present=False`` column shows its message + a placeholder cell."""
    present = ReportJobEntry(
        job_id=1,
        job_label="Job 0000001 · run a",
        state="complete",
        participant_label="Scenario A",
        inputs={"temperature": 100},
    )
    missing = ReportJobEntry(
        job_id=0,
        job_label="",
        state="",
        participant_label="Scenario B",
        present=False,
        missing_message="This tool isn't part of this scenario.",
    )
    text = build_compare_report(
        descriptor=_descriptor(),
        jobs=[present, missing],
        differing_keys=set(),
        csv_outputs=[],
        theme="dark",
    ).decode("utf-8")
    assert "Scenario A" in text
    assert "Scenario B" in text
    # The apostrophe in the message is HTML-escaped, so match a safe substring.
    assert "part of this scenario." in text
    assert 'class="placeholder"' in text


def test_multi_group_report_renders_a_section_per_group() -> None:
    """The overall (scenario/workflow) report headings each group + a shared header."""
    groups = [
        ReportGroup(
            descriptor=_descriptor(),
            jobs=_two_jobs(),
            differing_keys=set(),
            csv_outputs=[],
            heading="Material Properties",
        ),
        ReportGroup(
            descriptor=_descriptor(),
            jobs=_two_jobs(),
            differing_keys=set(),
            csv_outputs=[],
            heading="Heat Transfer",
        ),
    ]
    text = build_multi_compare_report(
        title="Compare report — scenarios",
        subtitle="2 scenarios · Variant A, Variant B",
        groups=groups,
        theme="dark",
    ).decode("utf-8")
    assert "Compare report — scenarios" in text
    assert "2 scenarios · Variant A, Variant B" in text
    # Each group's heading renders as a section <h2> in multi-group mode.
    assert "<h2>Material Properties</h2>" in text
    assert "<h2>Heat Transfer</h2>" in text


def test_report_embeds_html_outputs() -> None:
    """HTML outputs (e.g. a tool-written heatmap) render in the report.

    A non-plotly HTML embeds via ``<iframe srcdoc>``; a plotly
    ``write_html`` would instead have its figure extracted (covered by
    the on-screen path). Either way the "HTML outputs" section appears.
    """
    html_bytes = b"<html><body><h1>Heatmap summary</h1></body></html>"
    htmls = [
        JobHtmlOutput(
            job_id=1001,
            job_label="Job 0001001 · run a",
            html_name="heatmap",
            html_filename="heatmap.html",
            content=html_bytes,
        ),
    ]
    text = build_compare_report(
        descriptor=_descriptor(),
        jobs=_two_jobs(),
        differing_keys=set(),
        csv_outputs=[],
        html_outputs=htmls,
        theme="dark",
    ).decode("utf-8")
    assert "HTML outputs" in text
    assert "heatmap.html" in text
    assert "<iframe" in text


