def test_field_animations_in_html_but_not_pdf() -> None:
    """Field animations embed in the HTML download; the PDF flavour drops them."""
    html_text = build_compare_report(
        descriptor=_descriptor(),
        jobs=_two_jobs(),
        differing_keys=set(),
        csv_outputs=[],
        field_outputs=_field_outputs(),
        theme="dark",
        auto_print=False,
    ).decode("utf-8")
    pdf_text = build_compare_report(
        descriptor=_descriptor(),
        jobs=_two_jobs(),
        differing_keys=set(),
        csv_outputs=[],
        field_outputs=_field_outputs(),
        theme="dark",
        auto_print=True,
    ).decode("utf-8")
    assert "Field animations" in html_text
    # The animation renders as a plotly figure carrying its own play control.
    assert "plotly-graph-div" in html_text
    assert "Play" in html_text
    assert "Field animations" not in pdf_text


