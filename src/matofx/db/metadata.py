"""Single :class:`sqlalchemy.MetaData` instance for every MATOFX ORM model.

Every domain table registers against this :data:`metadata` so that
Alembic autogenerate sees them. Phase 0 ships the metadata object only
(no tables yet); domain models land in Phase 1 alongside the hierarchy
and tool plugin code.

Naming convention is set explicitly so constraint names are stable and
predictable across both SQLite and Postgres — autogenerated names from
SQLAlchemy differ subtly between dialects, which makes migrations
non-portable. Setting an explicit convention solves that.
"""

from __future__ import annotations

from sqlalchemy import MetaData

NAMING_CONVENTION: dict[str, str] = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

metadata = MetaData(naming_convention=NAMING_CONVENTION)
