"""Tool registry — descriptors, states, install / list / promote / archive.

Phase 1 ships the catalog half of the tool plugin model: descriptor
schema (port from legacy), Tool ORM with the New / Test / Released
state machine + soft-archive lifecycle, and a :class:`ToolService`
that installs / updates / archives / lists / gets / promotes tools
with permission-based visibility filtering and audited mutations.

The execution backend (subprocess-based MVP for Phase 1; synthesised-
image containerised execution for v1.0 per §F29) wires up in a
follow-up step alongside the file-staging layer.

Public surface:

- :class:`ToolDescriptor` — the complete tool contract.
- Sub-models: :class:`InputField`, :class:`InputGroup`,
  :class:`OutputField`, :class:`OutputGroup`,
  :class:`ResourceRequirements`, :class:`LicenceRequirement`,
  :class:`ExecutionBackend`, :class:`SumCheck`.
- :class:`Tool` — ORM row.
- :class:`ToolService` + :func:`make_tool_service` — registry CRUD.
- :func:`load_descriptor` + :func:`install_from_path` — bundle-on-disk loaders.
- :func:`list_tools_referencing_approver`, :func:`remove_approver_from_tools`
  — cross-module helpers used by :class:`matofx.users.UserService`.
- :data:`TOOL_STATES`, :data:`DEFAULT_TOOL_STATE`,
  :func:`user_can_see_state` — state model and the permission-driven
  visibility helper.
- :class:`ToolError` and subclasses — plain-English errors.
"""

